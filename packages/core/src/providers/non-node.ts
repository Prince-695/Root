/** Pure Go net/http project — zero Node project files. */
export async function structureizeGoHttp(options: {
  targetDir: string;
  answers: InitAnswers;
}): Promise<StructureizeResult> {
  const { targetDir, answers } = options;
  const filesWritten: string[] = [];
  const name = answers.projectName;
  const module = `example.com/${name}`;

  await write(
    targetDir,
    "go.mod",
    `module ${module}

go 1.22
${answers.orm === "gorm" ? "\nrequire gorm.io/gorm v1.25.12\n" : ""}`,
    filesWritten,
  );

  await write(
    targetDir,
    "main.go",
    `package main

import (
  "encoding/json"
  "log"
  "net/http"
)

func main() {
  mux := http.NewServeMux()
  mux.HandleFunc("/health", func(w http.ResponseWriter, r *http.Request) {
    w.Header().Set("Content-Type", "application/json")
    _ = json.NewEncoder(w).Encode(map[string]bool{"ok": true})
  })
  log.Println("listening on :8080")
  log.Fatal(http.ListenAndServe(":8080", mux))
}
`,
    filesWritten,
  );

  await write(
    targetDir,
    "README.md",
    `# ${name}

Generated by Root (Go net/http). No Node.js project files.

\`\`\`bash
go mod tidy
go run .
\`\`\`
`,
    filesWritten,
  );

  const rootJson = answersToRootJson({
    ...answers,
    language: "go",
    framework: "go-http",
    validation: "none",
    testing: "none",
    packageManager: "go-mod",
  });
  rootJson.aliases = {
    routes: ".",
    controllers: ".",
    services: ".",
    middleware: ".",
    schema: "main.go",
    server: "main.go",
    db: ".",
  };
  const rootJsonPath = await writeRootJson(targetDir, rootJson);
  filesWritten.push("root.json");
  await assertNoNodeProjectFiles(targetDir);
  return { filesWritten, rootJsonPath };
}
